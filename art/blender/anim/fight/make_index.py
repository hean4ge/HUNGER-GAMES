"""
make_index.py - writes FightClips/init.lua (the index of every fight clip) from the family modules beside it.

    python make_index.py <src/ReplicatedStorage/Shared/FightClips>
"""
import os
import re
import sys

DIR = sys.argv[1]
FAMILIES = ["Common", "Fists", "ShortBlade", "Sword", "Axe", "Spear", "Throwing", "Bow"]
names = {}
sizes = {}
for fam in FAMILIES:
    p = os.path.join(DIR, fam + ".lua")
    if not os.path.exists(p):
        continue
    sizes[fam] = os.path.getsize(p)
    with open(p, encoding="utf-8") as fh:
        for m in re.finditer(r"^\t\t(\w+) = \{$", fh.read(), re.M):
            names[m.group(1)] = fam

lines = ["--[[",
         "\tFightClips - the Combat v3 fight clips (docs/design/Combat_v3.md section 7), baked in Blender by",
         "\tart/blender/anim/fight/build_fight_clips.py, played by Client/Controllers/ClipPlayer. Generated by make_index.py.",
         "\tOne child module per family, required on first use (a family is loaded when one of its clips is first played).",
         "",
         "\tFightClips.get(name) -> raw clip { len, dt, n, mask, hit?, loop?, additive?, item?, kind, markers, tp, fp?, family }",
         "\tFightClips.FAMILY_OF[name] -> family        FightClips.WEAPON[itemId] -> family",
         "\tFightClips.forMove(itemId, move, n?) -> clip name?   move: \"Light\" (n = chain step), \"HeavyCharge\", \"Heavy\",",
         "\t    \"Counter\", \"Skill\", \"Throw\", \"ThrowWind\", \"Equip\", or a shared move (\"Kick\", \"Parry\", \"GuardIn\" ...: Common)",
         "]]",
         "local FightClips = {}", "",
         "FightClips.SIZES = { " + ", ".join("%s = %d" % (k, v) for k, v in sizes.items()) + " }",
         "FightClips.FAMILY_OF = {"]
for n in sorted(names):
    lines.append("\t%s = \"%s\"," % (n, names[n]))
lines += ["}", "",
          "FightClips.WEAPON = {",
          "\tfists = \"Fists\", knife = \"ShortBlade\", leaf_dagger = \"ShortBlade\", ring_blade = \"ShortBlade\",",
          "\tsword = \"Sword\", machete = \"Sword\", paired_blades = \"Sword\", wrapped_sabre = \"Sword\",",
          "\thatchet = \"Axe\", twin_axe = \"Axe\", climb_pick = \"Axe\", spear = \"Spear\", throwing_knife = \"Throwing\",",
          "\tbow = \"Bow\", short_bow = \"Bow\",",
          "}",
          "-- the clip-name prefix of each weapon's own chain",
          "FightClips.PREFIX = {",
          "\tfists = \"fists\", knife = \"knife\", leaf_dagger = \"dagger\", ring_blade = \"ring\", sword = \"sword\", machete = \"machete\",",
          "\tpaired_blades = \"paired\", wrapped_sabre = \"sword\", hatchet = \"hatchet\", twin_axe = \"twinaxe\", climb_pick = \"pick\",",
          "\tspear = \"spear\",",
          "}",
          "-- heavy / counter / skill clips by family (a weapon's own first, then its family's)",
          "local FAMILY_PREFIX = { Fists = \"fists\", ShortBlade = \"shortblade\", Sword = \"sword\", Axe = \"axe\", Spear = \"spear\" }",
          "local SKILL = { Fists = \"fists_skill_head_kick\", ShortBlade = \"shortblade_skill_chained\", Sword = \"sword_skill_running_cut\",",
          "\tAxe = \"axe_skill_whirl\", Spear = \"spear_skill_vault_kick\" }",
          "local THROW = { throwing_knife = \"throw_knife\", leaf_dagger = \"throw_dagger\", ring_blade = \"throw_ring\",",
          "\thatchet = \"throw_hatchet\", spear = \"throw_spear\", twin_axe = \"throw_twinaxe\" }",
          "local COMMON = { Kick = \"kick\", Parry = \"parry\", GuardIn = \"guard_in\", GuardHold = \"guard_hold\", GuardOut = \"guard_out\",",
          "\tBlockHit = \"block_hit\", GuardBreak = \"guard_break\", DodgeBack = \"dodge_back\", DodgeLeft = \"dodge_left\",",
          "\tDodgeRight = \"dodge_right\", DodgeRoll = \"dodge_roll\", Knockdown = \"knockdown\", Getup = \"getup\" }",
          "",
          "local cache = {}",
          "function FightClips.get(name: string): any",
          "\tlocal fam = FightClips.FAMILY_OF[name]",
          "\tif not fam then",
          "\t\treturn nil",
          "\tend",
          "\tlocal mod = cache[fam]",
          "\tif mod == nil then",
          "\t\tlocal child = script:FindFirstChild(fam)",
          "\t\tlocal ok, res = pcall(require, child :: any)",
          "\t\tmod = if ok and type(res) == \"table\" then res else false",
          "\t\tif not ok then",
          "\t\t\twarn(\"[FightClips] \" .. fam .. \": \" .. tostring(res))",
          "\t\tend",
          "\t\tcache[fam] = mod",
          "\tend",
          "\tlocal clip = mod and mod.clips[name]",
          "\tif clip and clip.family == nil then",
          "\t\tclip.family = fam",
          "\tend",
          "\treturn clip",
          "end",
          "",
          "local function exists(name: string?): string?",
          "\treturn if name and FightClips.FAMILY_OF[name] then name else nil",
          "end",
          "",
          "function FightClips.forMove(itemId: string, move: string, n: number?): string?",
          "\tlocal fam = FightClips.WEAPON[itemId]",
          "\tlocal prefix = FightClips.PREFIX[itemId]",
          "\tif move == \"Light\" and prefix then",
          "\t\treturn exists(prefix .. \"_light_\" .. tostring(n or 1))",
          "\telseif move == \"HeavyCharge\" or move == \"Heavy\" or move == \"Counter\" then",
          "\t\tlocal suffix = if move == \"HeavyCharge\" then \"_heavy_charge\" elseif move == \"Heavy\" then \"_heavy\" else \"_counter\"",
          "\t\treturn exists(prefix and prefix .. suffix) or exists(fam and FAMILY_PREFIX[fam] and FAMILY_PREFIX[fam] .. suffix)",
          "\t\t\tor exists(fam == \"Axe\" and \"axe\" .. suffix or nil)",
          "\telseif move == \"Skill\" then",
          "\t\treturn exists(fam and SKILL[fam])",
          "\telseif move == \"Throw\" then",
          "\t\treturn exists(THROW[itemId])",
          "\telseif move == \"ThrowWind\" then",
          "\t\treturn exists(\"throw_wind\")",
          "\telseif move == \"Equip\" then",
          "\t\treturn exists(fam and \"equip_\" .. string.lower(fam))",
          "\tend",
          "\treturn exists(COMMON[move])",
          "end",
          "",
          "return FightClips", ""]
with open(os.path.join(DIR, "init.lua"), "w", encoding="utf-8", newline="\n") as fh:
    fh.write("\n".join(lines))
print("index: %d clips in %d families; sizes %s" % (len(names), len(sizes), sizes))
