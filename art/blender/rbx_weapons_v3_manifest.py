"""Write src/ServerStorage/WorldGen/WeaponsV3Assets/Manifest.lua from art/manifests/WeaponsV3.manifest.json.

Run from the repo root:  python art/blender/rbx_weapons_v3_manifest.py
Only the near set is listed (the far set is uploaded and kept raw in ServerStorage.MeshImports, unused).
"""
import json
import os
import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "art", "manifests", "WeaponsV3.manifest.json")
OUT = os.path.join(ROOT, "src", "ServerStorage", "WorldGen", "WeaponsV3Assets", "Manifest.lua")


def num(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def vec(t):
    return "{" + ", ".join(num(x) for x in t) + "}"


def main():
    d = json.load(open(SRC))
    up = d.get("uploads", {})
    near = up.get("WeaponsV3.glb", {})
    lines = []
    w = lines.append
    stamp = datetime.datetime.utcnow().strftime("%Y-%m-%dT%H:%M:%SZ")
    w("--[[")
    w("\tWeaponsV3Assets.Manifest - GENERATED by art/blender/rbx_weapons_v3_manifest.py on %s from" % stamp)
    w("\tart/manifests/WeaponsV3.manifest.json. Do not edit by hand. Item space: Grip at the origin, the item along +Y,")
    w("\tedge / front toward -Z (Roblox axes). P(name, role, finishRole, {r,g,b}); A(position, look, up).")
    w("]]")
    w("local function P(name, role, finish, rgb)")
    w("\treturn { name = name, role = role, finish = finish, rgb = rgb }")
    w("end")
    w("local function A(pos, look, up)")
    w("\treturn { pos = pos, look = look, up = up }")
    w("end")
    w("return {")
    w("\tSOURCE = { assetId = %s, name = \"%s\", file = \"WeaponsV3.glb\" }," % (
        near.get("assetId") or "nil", near.get("displayName") or "LS_WeaponsV3_v1"))
    w("\tItems = {")
    for a in d["assets"]:
        if a["name"].endswith("_Far"):
            continue
        w("\t\t[\"%s\"] = {" % a["name"])
        w("\t\t\tid = \"%s\", stars = %s, kind = \"%s\", origin = %s, bmin = %s, bmax = %s," % (
            a["id"], a["stars"] if a.get("stars") else "nil", a.get("kind", ""), vec(a["origin"]),
            vec(a["boundsMin"]), vec(a["boundsMax"])))
        w("\t\t\tparts = {")
        for p in a["parts"]:
            w("\t\t\t\tP(\"%s\", \"%s\", \"%s\", %s)," % (p["name"], p["role"], p.get("finishRole", ""), vec(p["rgb"])))
        w("\t\t\t},")
        w("\t\t\tatt = {")
        for k, v in a["attachments"].items():
            w("\t\t\t\t%s = A(%s, %s, %s)," % (k, vec(v["position"]), vec(v["look"]), vec(v["up"])))
        w("\t\t\t},")
        w("\t\t},")
    w("\t},")
    w("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT, len(lines), "lines")


if __name__ == "__main__":
    main()
