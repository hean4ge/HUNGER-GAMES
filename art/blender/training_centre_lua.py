"""
training_centre_lua.py - writes src/ServerStorage/WorldGen/TrainingCentreData.lua from the Training Centre export
(TrainingCentre.manifest.json + TrainingCentre.prims.json), for WorldGen.TrainingCentreBuilder.

Run from the repo root (plain Python 3, no Blender):
  python art/blender/training_centre_lua.py [<export dir>]
The export dir defaults to %USERPROFILE%/OneDrive/Documents/LastStanding/BlenderExports/TrainingCentre. If
art/manifests/TrainingCentre.manifest.json carries assetIds (the upload record), its model asset id is used.
"""
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
EXP = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.expanduser("~"), "OneDrive", "Documents",
                                                          "LastStanding", "BlenderExports", "TrainingCentre")
OUT = os.path.join(REPO, "src", "ServerStorage", "WorldGen", "TrainingCentreData.lua")


def num(x):
    if isinstance(x, bool):
        return "true" if x else "false"
    if isinstance(x, int):
        return str(x)
    s = ("%.4f" % x).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def lua(v):
    if v is None:
        return "nil"
    if isinstance(v, (bool, int, float)):
        return num(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "{" + ",".join(lua(x) for x in v) + "}"
    if isinstance(v, dict):
        out = []
        for k, x in v.items():
            key = k if k.isidentifier() else "[%s]" % json.dumps(k)
            out.append("%s=%s" % (key, lua(x)))
        return "{" + ",".join(out) + "}"
    raise TypeError(type(v))


def main():
    with open(os.path.join(EXP, "TrainingCentre.manifest.json"), encoding="utf-8") as fh:
        man = json.load(fh)
    with open(os.path.join(EXP, "TrainingCentre.prims.json"), encoding="utf-8") as fh:
        prims = json.load(fh)["assets"]
    repo_man = os.path.join(REPO, "art", "manifests", "TrainingCentre.manifest.json")
    ids = man.get("assetIds")
    if os.path.exists(repo_man):
        with open(repo_man, encoding="utf-8") as fh:
            ids = json.load(fh).get("assetIds") or ids
    asset_id = (ids or {}).get("model", {}).get("assetId")
    lines = []
    w = lines.append
    w("-- GENERATED by art/blender/training_centre_lua.py from TrainingCentre.manifest.json + .prims.json. Do not edit.")
    w("-- Hall space (Roblox axes, studs); every zone asset is placed at the hall origin. See TrainingCentreBuilder.")
    w("local D = {}")
    w("D.assetId = %s" % (num(asset_id) if asset_id else "nil"))
    w("D.glb = %s" % lua({k: man["glbCheck"][k] for k in ("bytes", "meshes", "triangles")}))
    w("D.hallOrigin = %s" % lua(man["hallOrigin"]))
    w("D.triangles = %s" % lua({"unique": man["triangles"]["unique"], "drawn": man["triangles"]["drawnAllCopies"]}))
    w("D.assets = {}")
    for a in man["assets"]:
        roles = {}
        for p in a["parts"]:
            r = {"n": p["name"], "m": p["robloxMaterial"], "c": p["rgb"], "p": p["center"]}
            if p["transparency"]:
                r["t"] = p["transparency"]
            if not p["castShadow"]:
                r["sh"] = False
            if p["tags"]:
                r["tags"] = p["tags"]
            roles[p["role"]] = r
        cols = []
        for c in a["colliders"]:
            d = {"n": c["name"], "p": c["center"], "s": c["size"]}
            if c["yawDeg"]:
                d["yaw"] = c["yawDeg"]
            if c["tags"]:
                d["tags"] = c["tags"]
            if c["attributes"]:
                d["at"] = c["attributes"]
            cols.append(d)
        att = {}
        for k, v in a["attachments"].items():
            d = {"p": v["position"], "l": v["look"], "u": v["up"]}
            if v.get("attributes"):
                d["at"] = v["attributes"]
            att[k] = d
        pls = [{"name": pl["name"], "p": pl["position"], "yaw": pl["yawDeg"],
                **({"station": pl["station"]} if pl.get("station") else {}),
                **({"role": pl["role"]} if pl.get("role") else {})} for pl in a["placements"]]
        w("D.assets[%s] = {" % json.dumps(a["name"]))
        w("  kind = %s, tris = %d," % (json.dumps(a["kind"]), a["tris"]))
        w("  placements = %s," % lua(pls))
        w("  roles = %s," % lua(roles))
        w("  colliders = %s," % lua(cols))
        w("  attachments = %s," % lua(att))
        w("  prims = {")
        for role, rows in prims.get(a["name"], {}).items():
            w("    [%s] = {%s}," % (json.dumps(role), ",".join(lua(r) for r in rows)))
        w("  },")
        w("}")
    w("D.order = %s" % lua([a["name"] for a in man["assets"]]))
    w("return D")
    src = "\n".join(lines) + "\n"
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(src)
    print("WROTE", OUT, len(src.encode("utf-8")), "bytes; assetId", asset_id)


main()
