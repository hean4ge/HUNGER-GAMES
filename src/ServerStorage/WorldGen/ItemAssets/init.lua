--[[
	ItemAssets - edit-time builder for the item templates in ReplicatedStorage.Assets:
	  Assets.Items.<itemId>          held items     (ReplicatedStorage.Shared.ItemModels.build clones these)
	  Assets.Crates.SupplyCrate1..3  supply crates  (ItemModels.buildCrate)
	Source art: ItemsReal.glb (art/blender/items_real.py), uploaded once as the Model asset LS_ItemsReal_v1
	(Manifest.SOURCES.Items): a drop-in for the v1 Items.glb with the same names, origins, attachments and the part
	names the game relies on. Surfaces use one shared image id per PNG (Manifest.IMAGES: ColorMap / NormalMap are the
	importer's own uploads, verified pixel-exact; RoughnessMap / MetalnessMap the separate grayscale PNGs; ledger
	art/manifests/RealSets.assetIds.json). The raw insert is kept in ServerStorage.MeshImports (a package; never edit
	it; build() loads it with InsertService when missing). Everything else comes from the Manifest child, generated by
	art/blender/rbx_items_manifest.py. Repo copies: art/manifests/ItemAssets.luau and ItemAssets.Manifest.luau.
	Nothing here runs at game time. (The v1 Items.glb builder, which also built the unused Assets.Viewmodel arms, is
	kept as ServerStorage.Archive_v1.ItemAssets_v1.)

	Run in Edit mode (require a Clone so Studio does not serve a cached copy):
	  print(require(game.ServerStorage.WorldGen.ItemAssets:Clone()).build())    -- ~15 s
	  print(require(game.ServerStorage.WorldGen.ItemAssets:Clone()).verify())   -- read-back check against the manifest
	build() never destroys published templates: v1 Items.glb ones (Source = LS_Items_v1) go to
	ServerStorage.Archive_v1.ItemTemplates_v1.<Items|Crates>, earlier builds of this builder to
	Archive_v1.ItemAssets_prev.<Items|Crates> (only the latest previous build is kept there).

	Item templates. Item space is the export's: Grip at the origin, the item along +Y, edge / front toward -Z.
	  Handle   invisible 0.05-stud Part at CFrame.identity, PrimaryPart: the Grip point turned into the ItemModels
	           convention (HANDLE_FRAME): LookVector = business end, UpVector = blade spine (edges face -UpVector),
	           RightVector = blade flat; the bow's UpVector is its shooting direction; vests and the med kit hang
	           along LookVector with their decorated front on -RightVector.
	  MeshParts named as in the manifest, welded to Handle, Massless, CanCollide / CanQuery / CanTouch off, one
	           SurfaceAppearance each (manifest maps, AlphaMode, tint; glass and water AlphaMode Transparency with
	           Transparency 0.02), DoubleSided off, RenderFidelity Automatic, CollisionFidelity from the manifest (Box),
	           attribute Role. bow_Rope (string, serving, nock bead) has attribute String: the "view" variant swaps it
	           for two Beams.
	  Attachments in Handle: Grip (identity) and the manifest's Tip, Nock, StringTop, StringBottom, ArrowRest, Mouth,
	           Torso. The bow's Nock has attributes RestPosition (Handle space) and MaxDraw (studs).
	  Attributes ItemId, Kind, Source (the raw insert's name), AssetId (the GLB's Model asset).
	Crate templates (anchored; crate space: bottom centre at the origin, front -Z):
	  Base     invisible WoodPlanks collision box round the crate body (PrimaryPart; CanCollide, CanQuery) with
	           attachments PromptAttachment, LootPoint (tier 3: a small EmberGlow light) and LidHinge.
	  Lid      the lid mesh (collides) with the Lid-tagged fittings as children; the body meshes are visual only;
	           SupplyCrate3_Ember is Neon with no SurfaceAppearance.
	  Attributes Tier, Opened = false, Hinge (CFrame relative to Base; turn the lid about its X axis to open), Source,
	           AssetId.
]]
local AssetService = game:GetService("AssetService")
local InsertService = game:GetService("InsertService")
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local ServerStorage = game:GetService("ServerStorage")

local Manifest = require(script:WaitForChild("Manifest"))

local ItemAssets = {}
ItemAssets.SOURCES = Manifest.SOURCES
ItemAssets.V1_SOURCE = "LS_Items_v1" -- the v1 Items.glb templates (archived, never overwritten)

-- Handle frames in item space (rotation only; the Grip is at the item origin).
local HANDLE = {
	default = CFrame.fromMatrix(Vector3.zero, Vector3.xAxis, Vector3.zAxis), -- Look +Y, Up +Z (spine), Right +X (flat)
	bow = CFrame.fromMatrix(Vector3.zero, -Vector3.xAxis, -Vector3.zAxis), -- Look +Y (top limb), Up -Z (shooting)
	hang = CFrame.fromMatrix(Vector3.zero, Vector3.zAxis, Vector3.xAxis), -- Look -Y (hangs below), Right +Z (front = -Right)
}
ItemAssets.HANDLE_FRAME = { bow = HANDLE.bow, medkit = HANDLE.hang, leather_vest = HANDLE.hang, padded_armor = HANDLE.hang }

local BOW_MAX_DRAW = 1.12 -- studs (the mesh bow's own draw; the view pulls Config.Combat.ViewBowDraw)
local HANDLE_SIZE = Vector3.new(0.05, 0.05, 0.05)
local CRATE_LIGHT = Color3.fromRGB(255, 138, 64)
local BOUNDS_TOLERANCE = 0.06 -- studs, template bounds vs manifest bmin / bmax

local function vec(t: { number }): Vector3
	return Vector3.new(t[1], t[2], t[3])
end
local function rgb(t: { number }): Color3
	return Color3.fromRGB(t[1], t[2], t[3])
end

-- World-axis bounds of a box of `size` at `frame`.
local function boxBounds(frame: CFrame, size: Vector3): (Vector3, Vector3)
	local h = size / 2
	local r = frame.Rotation
	local e = Vector3.new(
		math.abs(r.RightVector.X) * h.X + math.abs(r.UpVector.X) * h.Y + math.abs(r.LookVector.X) * h.Z,
		math.abs(r.RightVector.Y) * h.X + math.abs(r.UpVector.Y) * h.Y + math.abs(r.LookVector.Y) * h.Z,
		math.abs(r.RightVector.Z) * h.X + math.abs(r.UpVector.Z) * h.Y + math.abs(r.LookVector.Z) * h.Z
	)
	return frame.Position - e, frame.Position + e
end

local function attachmentFrame(a: any): CFrame
	local pos = vec(a.pos)
	return CFrame.lookAt(pos, pos + vec(a.look), vec(a.up))
end

local function ensureFolder(parent: Instance, name: string): Folder
	local f = parent:FindFirstChild(name)
	if f and not f:IsA("Folder") then
		f = nil
	end
	if not f then
		f = Instance.new("Folder")
		f.Name = name
		f.Parent = parent
	end
	return f :: Folder
end

local function image(key: string?): string
	if not key then
		return ""
	end
	local id = Manifest.IMAGES[key]
	assert(id, "no image id for " .. tostring(key))
	return "rbxassetid://" .. tostring(id)
end

-- The raw insert (kept in ServerStorage.MeshImports, loaded once if missing).
local function sourceModel(): Instance
	local info = Manifest.SOURCES.Items
	local imports = ensureFolder(ServerStorage, "MeshImports")
	local existing = imports:FindFirstChild(info.name)
	if existing then
		return existing
	end
	local loaded = InsertService:LoadAsset(info.assetId)
	local root = loaded:GetChildren()[1] or loaded
	root.Name = info.name
	root.Parent = imports
	if loaded ~= root then
		loaded:Destroy()
	end
	return root
end

-- Where each asset sits inside the raw import, as its pivot frame (origin and axes, world space). The importer keeps
-- the GLB layout (assets in a row along +X) but turns it about the vertical axis and bakes the turn into the mesh
-- data (every MeshPart reads the same rotation R0: identity from the importer, or the yaw insert_asset gave the
-- model). In R0's frame the parts are axis-aligned; the baked turn is read off the row and must be a multiple of 90
-- degrees. Returns asset name -> pivot CFrame and a list of problems.
local function locateAssets(index: { [string]: MeshPart }): ({ [string]: CFrame }, { string })
	local assets = Manifest.Items
	local problems = {}
	local centres, sizes = {}, {}
	local R0: CFrame? = nil
	for _, a in pairs(assets) do
		for _, p in ipairs(a.parts) do
			if index[p.name] then
				R0 = index[p.name].CFrame.Rotation
				break
			end
		end
		if R0 then
			break
		end
	end
	local base = R0 or CFrame.identity
	local toLocal = base:Inverse()
	for name, a in pairs(assets) do
		local lo = Vector3.new(math.huge, math.huge, math.huge)
		local hi = -lo
		local found = 0
		for _, p in ipairs(a.parts) do
			local part = index[p.name]
			if part then
				found += 1
				local rel = toLocal * part.CFrame
				if rel.LookVector.Z > -0.9999 or rel.UpVector.Y < 0.9999 then
					table.insert(problems, p.name .. " is turned differently from the rest of the import")
				end
				lo = lo:Min(rel.Position - part.Size / 2)
				hi = hi:Max(rel.Position + part.Size / 2)
			else
				table.insert(problems, "missing mesh " .. p.name)
			end
		end
		if found > 0 then
			centres[name] = (lo + hi) / 2
			sizes[name] = hi - lo
		end
	end
	local first, last
	for name, a in pairs(assets) do
		if centres[name] then
			if not first or a.origin[1] < assets[first].origin[1] then
				first = name
			end
			if not last or a.origin[1] > assets[last].origin[1] then
				last = name
			end
		end
	end
	local function manifestCentre(name: string): Vector3
		local a = assets[name]
		return vec(a.origin) + (vec(a.bmin) + vec(a.bmax)) / 2
	end
	local yaw = 0
	if first and last and first ~= last then
		local dm = manifestCentre(last) - manifestCentre(first)
		local dw = centres[last] - centres[first]
		yaw = math.atan2(-dw.Z, dw.X) - math.atan2(-dm.Z, dm.X)
		local snapped = math.round(yaw / (math.pi / 2)) * (math.pi / 2)
		if math.abs(snapped - yaw) > math.rad(1) then
			table.insert(problems, string.format("import turned %.1f degrees (not a multiple of 90)", math.deg(yaw)))
		end
		yaw = snapped
	end
	local R = CFrame.Angles(0, yaw, 0)
	local pivots = {}
	for name, a in pairs(assets) do
		if centres[name] then
			pivots[name] = base * CFrame.new(centres[name] - R:VectorToWorldSpace((vec(a.bmin) + vec(a.bmax)) / 2)) * R
			local size = R:VectorToObjectSpace(sizes[name])
			size = Vector3.new(math.abs(size.X), math.abs(size.Y), math.abs(size.Z))
			if (size - (vec(a.bmax) - vec(a.bmin))).Magnitude > 0.02 then
				table.insert(problems, string.format("%s measures %s, manifest %s", name, tostring(size), tostring(vec(a.bmax) - vec(a.bmin))))
			end
		end
	end
	if math.abs(yaw) > 1e-3 then
		table.insert(problems, string.format("(note) the meshes are turned %d degrees about Y inside the import; corrected", math.round(math.deg(yaw))))
	end
	return pivots, problems
end

-- CollisionFidelity ignores direct writes (it stays Default, silently). The physics is made at the manifest's fidelity
-- with AssetService:CreateMeshPartAsync (~1.4 s per mesh, 8 at once) and copied onto the part with ApplyMesh.
local function prefetchPhysics(index: { [string]: MeshPart }): { [string]: MeshPart }
	local jobs = {}
	for _, a in pairs(Manifest.Items) do
		for _, info in ipairs(a.parts) do
			local source = index[info.name]
			local fidelity = (Enum.CollisionFidelity :: any)[info.collision] or Enum.CollisionFidelity.Box
			if source and source.CollisionFidelity ~= fidelity then
				table.insert(jobs, { name = info.name, content = source.MeshContent, fidelity = fidelity })
			end
		end
	end
	local results: { [string]: MeshPart } = {}
	local running, nextJob = 0, 1
	while nextJob <= #jobs or running > 0 do
		while running < 8 and nextJob <= #jobs do
			local job = jobs[nextJob]
			nextJob += 1
			running += 1
			task.spawn(function()
				local ok, tmp = pcall(function()
					return AssetService:CreateMeshPartAsync(job.content, { CollisionFidelity = job.fidelity, RenderFidelity = Enum.RenderFidelity.Automatic })
				end)
				if ok then
					results[job.name] = tmp
				end
				running -= 1
			end)
		end
		task.wait()
	end
	return results
end

-- A clean copy of an imported mesh with the manifest's surface and flags; `frame` is its CFrame in the template.
local function meshCopy(source: MeshPart, info: any, frame: CFrame, physics: { [string]: MeshPart }): MeshPart
	local part = source:Clone()
	for _, child in ipairs(part:GetChildren()) do
		child:Destroy() -- importer leftovers (its SurfaceAppearance with packed-map roughness, welds, attachments)
	end
	local tmp = physics[info.name]
	if tmp then
		part:ApplyMesh(tmp)
		tmp:Destroy()
		physics[info.name] = nil
	end
	part.Name = info.name
	part.TextureID = ""
	pcall(function()
		part.DoubleSided = false
	end)
	pcall(function()
		part.RenderFidelity = Enum.RenderFidelity.Automatic
	end)
	part.Reflectance = 0
	part.CastShadow = info.shadow and not info.neon
	part.Color = rgb(info.rgb) -- the mean texture colour (fallback)
	if info.neon then
		part.Material = Enum.Material.Neon
		part.Transparency = 0
	else
		part.Material = (Enum.Material :: any)[info.mat] or Enum.Material.SmoothPlastic
		part.Transparency = info.transparency
		local s = Manifest.SURF[info.surf]
		local sa = Instance.new("SurfaceAppearance")
		sa.ColorMap = image(s[1])
		sa.NormalMap = image(s[2])
		sa.RoughnessMap = image(s[3])
		sa.MetalnessMap = image(s[4] or nil)
		sa.AlphaMode = (Enum.AlphaMode :: any)[info.alpha] or Enum.AlphaMode.Overlay
		sa.Color = rgb(info.tint)
		sa.Parent = part
	end
	part.CFrame = frame
	part:SetAttribute("Role", info.role)
	return part
end

local function setPhysics(part: BasePart, anchored: boolean, collide: boolean, query: boolean)
	part.Anchored = anchored
	part.CanCollide = collide
	part.CanQuery = query
	part.CanTouch = false
	part.Massless = not anchored
end

local function tagModel(model: Model)
	model:SetAttribute("Source", Manifest.SOURCES.Items.name)
	model:SetAttribute("AssetId", Manifest.SOURCES.Items.assetId)
end

local function buildItem(name: string, a: any, index: { [string]: MeshPart }, pivot: CFrame, physics: any): Model
	local Hinv = (ItemAssets.HANDLE_FRAME[name] or HANDLE.default):Inverse()
	local toItem = pivot:Inverse()
	local model = Instance.new("Model")
	model.Name = name
	local handle = Instance.new("Part")
	handle.Name = "Handle"
	handle.Size = HANDLE_SIZE
	handle.Transparency = 1
	handle.CastShadow = false
	handle.CFrame = CFrame.identity
	handle.TopSurface = Enum.SurfaceType.Smooth
	handle.BottomSurface = Enum.SurfaceType.Smooth
	setPhysics(handle, false, false, false)
	handle.Parent = model
	model.PrimaryPart = handle
	for _, info in ipairs(a.parts) do
		local source = index[info.name]
		if source then
			local part = meshCopy(source, info, Hinv * (toItem * source.CFrame), physics)
			setPhysics(part, false, false, false)
			if name == "bow" and info.role == "Rope" then
				part:SetAttribute("String", true)
			end
			part.Parent = model
			local w = Instance.new("Weld")
			w.Name = "Weld"
			w.Part0 = handle
			w.Part1 = part
			w.C0 = part.CFrame
			w.Parent = part
		end
	end
	local grip = Instance.new("Attachment")
	grip.Name = "Grip"
	grip.Parent = handle
	for attName, att in pairs(a.att) do
		if attName ~= "Grip" then
			local at = Instance.new("Attachment")
			at.Name = attName
			at.CFrame = Hinv * attachmentFrame(att)
			at.Parent = handle
		end
	end
	if name == "bow" then
		local nock = handle:FindFirstChild("Nock") :: Attachment
		nock:SetAttribute("RestPosition", nock.Position)
		nock:SetAttribute("MaxDraw", BOW_MAX_DRAW)
	end
	model:SetAttribute("ItemId", name)
	model:SetAttribute("Kind", a.kind)
	tagModel(model)
	return model
end

local function buildCrate(name: string, tier: number, a: any, index: { [string]: MeshPart }, pivot: CFrame, physics: any): Model
	local toItem = pivot:Inverse()
	local model = Instance.new("Model")
	model.Name = name
	local body, fittings = {}, {}
	local lid: BasePart? = nil
	local lo = Vector3.new(math.huge, 0, math.huge)
	local hi = Vector3.new(-math.huge, -math.huge, -math.huge)
	for _, info in ipairs(a.parts) do
		local source = index[info.name]
		if source then
			local frame = toItem * source.CFrame
			local part = meshCopy(source, info, frame, physics)
			if info.name == name .. "_Lid" then
				part.Name = "Lid"
				setPhysics(part, true, true, true)
				lid = part
			elseif table.find(info.tags, "Lid") then
				setPhysics(part, true, false, false)
				table.insert(fittings, part)
			else
				setPhysics(part, true, false, false)
				table.insert(body, part)
				if info.collide then
					local a0, a1 = boxBounds(frame, part.Size)
					lo, hi = lo:Min(a0), hi:Max(a1)
				end
			end
		end
	end
	lo = Vector3.new(lo.X, 0, lo.Z)
	local size = hi - lo
	local base = Instance.new("Part")
	base.Name = "Base"
	base.Size = size
	base.CFrame = CFrame.new((lo + hi) / 2)
	base.Transparency = 1
	base.Material = Enum.Material.WoodPlanks -- arrow / melee hit sounds and footsteps read the collider's material
	base.CastShadow = false
	base.TopSurface = Enum.SurfaceType.Smooth
	base.BottomSurface = Enum.SurfaceType.Smooth
	setPhysics(base, true, true, true)
	base.Parent = model
	model.PrimaryPart = base
	for _, part in ipairs(body) do
		part.Parent = model
	end
	if lid then
		lid.Parent = model
		for _, part in ipairs(fittings) do
			part.Parent = lid
		end
	end
	local function addAttachment(attName: string, as: string): Attachment?
		local att = a.att[attName]
		if not att then
			return nil
		end
		local at = Instance.new("Attachment")
		at.Name = as
		at.CFrame = base.CFrame:Inverse() * attachmentFrame(att)
		at.Parent = base
		return at
	end
	addAttachment("Prompt", "PromptAttachment")
	local loot = addAttachment("LootPoint", "LootPoint")
	local hinge = addAttachment("LidHinge", "LidHinge")
	if tier == 3 and loot then
		local light = Instance.new("PointLight")
		light.Name = "EmberGlow"
		light.Color = CRATE_LIGHT
		light.Brightness = 0.6
		light.Range = 6
		light.Shadows = true
		light.Parent = loot
	end
	model:SetAttribute("Tier", tier)
	model:SetAttribute("Opened", false)
	model:SetAttribute("Hinge", if hinge then CFrame.new(hinge.Position) else CFrame.new(0, size.Y / 2, size.Z / 2))
	tagModel(model)
	return model
end

-- Puts `models` into <target>.Assets.<folderName>; a template it replaces is moved to the archive (see the header).
-- Staging builds into another target replace their own earlier copies.
local function publish(target: Instance, folderName: string, models: { Model }): (number, number)
	local folder = ensureFolder(ensureFolder(target, "Assets"), folderName)
	local archived, moved = 0, 0
	for _, m in ipairs(models) do
		local old = folder:FindFirstChild(m.Name)
		if old and target == ReplicatedStorage then
			local archive = ensureFolder(ServerStorage, "Archive_v1")
			if old:GetAttribute("Source") == ItemAssets.V1_SOURCE then
				local keep = ensureFolder(ensureFolder(archive, "ItemTemplates_v1"), folderName)
				if keep:FindFirstChild(old.Name) then
					old.Name ..= "_dup"
				end
				old.Parent = keep
				archived += 1
			else
				local prev = ensureFolder(ensureFolder(archive, "ItemAssets_prev"), folderName)
				local older = prev:FindFirstChild(old.Name)
				if older then
					older:Destroy() -- the build before last (generated output of this builder)
				end
				old.Parent = prev
				moved += 1
			end
		elseif old then
			old:Destroy() -- a staging copy from an earlier test build
		end
		m.Parent = folder
	end
	return archived, moved
end

-- options (for tests): source = <raw insert>, target = parent of the Assets folder (default ReplicatedStorage)
function ItemAssets.build(options: { source: Instance?, target: Instance? }?): string
	local t0 = os.clock()
	local source = (options and options.source) or sourceModel()
	local target = (options and options.target) or ReplicatedStorage
	local index = {}
	for _, d in ipairs(source:GetDescendants()) do
		if d:IsA("MeshPart") then
			index[d.Name] = d
		end
	end
	local pivots, problems = locateAssets(index)
	local physics = prefetchPhysics(index)
	local items, crates = {}, {}
	local meshes = 0
	for name, a in pairs(Manifest.Items) do
		local pivot = pivots[name]
		if pivot then
			local tier = tonumber(string.match(name, "^SupplyCrate(%d)$"))
			table.insert(if tier then crates else items, if tier then buildCrate(name, tier, a, index, pivot, physics) else buildItem(name, a, index, pivot, physics))
			meshes += #a.parts
		else
			table.insert(problems, name .. " not found in the import")
		end
	end
	for _, tmp in pairs(physics) do
		tmp:Destroy()
	end
	local a1, m1 = publish(target, "Items", items)
	local a2, m2 = publish(target, "Crates", crates)
	table.insert(problems, string.format("%d item templates, %d crates, %d meshes from %s in %.1f s (%d v1 templates archived, %d earlier builds moved to ItemAssets_prev)",
		#items, #crates, meshes, source.Name, os.clock() - t0, a1 + a2, m1 + m2))
	return table.concat(problems, "\n")
end

-- Read-back check of the published templates against the manifest; "0 problems" when clean.
function ItemAssets.verify(options: { target: Instance? }?): string
	local assets = ((options and options.target) or ReplicatedStorage):FindFirstChild("Assets")
	local problems = {}
	local function bad(fmt: string, ...)
		table.insert(problems, string.format(fmt, ...))
	end
	local n = { templates = 0, parts = 0, surfaces = 0, attachments = 0 }
	local function same(a: CFrame, b: CFrame): boolean
		return (a.Position - b.Position).Magnitude <= 1e-3 and (a.LookVector - b.LookVector).Magnitude <= 1e-3
			and (a.UpVector - b.UpVector).Magnitude <= 1e-3
	end
	local src = Manifest.SOURCES.Items
	for name, a in pairs(Manifest.Items) do
		local tier = tonumber(string.match(name, "^SupplyCrate(%d)$"))
		local folder = assets and assets:FindFirstChild(if tier then "Crates" else "Items")
		local model = folder and folder:FindFirstChild(name)
		local primary = model and model.PrimaryPart
		if not (primary and primary.Name == (if tier then "Base" else "Handle")) then
			bad("%s: no template or wrong PrimaryPart", name)
			continue
		end
		n.templates += 1
		if model:GetAttribute("Source") ~= src.name or model:GetAttribute("AssetId") ~= src.assetId then
			bad("%s: Source / AssetId", name)
		end
		-- template space -> manifest space (crates: the same; items: through the Handle frame)
		local toManifest = if tier then CFrame.identity else (ItemAssets.HANDLE_FRAME[name] or HANDLE.default) * primary.CFrame:Inverse()
		local lo = Vector3.new(math.huge, math.huge, math.huge)
		local hi = -lo
		for _, info in ipairs(a.parts) do
			local part = model:FindFirstChild(if tier and info.name == name .. "_Lid" then "Lid" else info.name, true)
			if not (part and part:IsA("MeshPart")) then
				bad("%s: missing part %s", name, info.name)
				continue
			end
			n.parts += 1
			local p0, p1 = boxBounds(toManifest * part.CFrame, part.Size)
			lo, hi = lo:Min(p0), hi:Max(p1)
			local sas = 0
			for _, child in ipairs(part:GetChildren()) do
				if child:IsA("SurfaceAppearance") then
					sas += 1
				elseif not (child:IsA("Weld") or child:IsA("MeshPart")) then
					bad("%s: leftover %s", info.name, child.ClassName)
				end
			end
			local sa = part:FindFirstChildOfClass("SurfaceAppearance")
			if info.neon then
				if sas > 0 or part.Material ~= Enum.Material.Neon then
					bad("%s: neon part has a SurfaceAppearance or is %s", info.name, part.Material.Name)
				end
			else
				local s = Manifest.SURF[info.surf]
				if sas ~= 1 or not sa then
					bad("%s: %d SurfaceAppearances", info.name, sas)
				else
					n.surfaces += 1
					if sa.ColorMap ~= image(s[1]) or sa.NormalMap ~= image(s[2]) or sa.RoughnessMap ~= image(s[3]) or sa.MetalnessMap ~= image(s[4] or nil) then
						bad("%s: maps differ", info.name)
					end
					if sa.AlphaMode.Name ~= info.alpha or sa.Color ~= rgb(info.tint) then
						bad("%s: AlphaMode %s / tint %s", info.name, sa.AlphaMode.Name, tostring(sa.Color))
					end
				end
				if math.abs(part.Transparency - info.transparency) > 1e-4 or part.Material.Name ~= info.mat then
					bad("%s: Transparency %.3f / Material %s", info.name, part.Transparency, part.Material.Name)
				end
			end
			if part.TextureID ~= "" or part.DoubleSided or part.CastShadow ~= (info.shadow and not info.neon) then
				bad("%s: TextureID / DoubleSided / CastShadow", info.name)
			end
			if part.CollisionFidelity.Name ~= info.collision then
				bad("%s: CollisionFidelity %s, want %s", info.name, part.CollisionFidelity.Name, info.collision)
			end
			if tier then
				if not part.Anchored then
					bad("%s: not anchored", info.name)
				end
			else
				local w = part:FindFirstChildOfClass("Weld")
				if part.Anchored or part.CanCollide or part.CanQuery or part.CanTouch or not part.Massless
					or not (w and w.Part0 == primary and w.Part1 == part) then
					bad("%s: held-item flags or weld", info.name)
				end
			end
		end
		if (lo - vec(a.bmin)).Magnitude > BOUNDS_TOLERANCE or (hi - vec(a.bmax)).Magnitude > BOUNDS_TOLERANCE then
			bad("%s: bounds %s .. %s, manifest %s .. %s", name, tostring(lo), tostring(hi), tostring(vec(a.bmin)), tostring(vec(a.bmax)))
		end
		if tier then
			for attName, as in pairs({ Prompt = "PromptAttachment", LootPoint = "LootPoint", LidHinge = "LidHinge" }) do
				local at = primary:FindFirstChild(as)
				if not at then
					bad("%s: no %s", name, as)
				else
					n.attachments += 1
					if not same(primary.CFrame * at.CFrame, attachmentFrame(a.att[attName])) then
						bad("%s.%s frame differs", name, as)
					end
				end
			end
			if not primary.CanCollide or not primary.CanQuery or primary.Transparency ~= 1 or primary.Material ~= Enum.Material.WoodPlanks
				or not model:FindFirstChild("Lid") or typeof(model:GetAttribute("Hinge")) ~= "CFrame" or model:GetAttribute("Tier") ~= tier then
				bad("%s: Base / Lid / Hinge / Tier", name)
			end
		else
			local Hinv = (ItemAssets.HANDLE_FRAME[name] or HANDLE.default):Inverse()
			for attName, want in pairs(a.att) do
				local at = primary:FindFirstChild(attName)
				if not at then
					bad("%s: no attachment %s", name, attName)
				else
					n.attachments += 1
					if not same(at.CFrame, if attName == "Grip" then CFrame.identity else Hinv * attachmentFrame(want)) then
						bad("%s.%s frame differs", name, attName)
					end
				end
			end
			if name == "bow" then
				local nock = primary:FindFirstChild("Nock")
				local rope = model:FindFirstChild("bow_Rope")
				if not (nock and typeof(nock:GetAttribute("RestPosition")) == "Vector3" and nock:GetAttribute("MaxDraw") and rope and rope:GetAttribute("String")) then
					bad("bow: Nock attributes / String")
				end
			end
			if model:GetAttribute("ItemId") ~= name or model:GetAttribute("Kind") ~= a.kind then
				bad("%s: ItemId / Kind", name)
			end
		end
	end
	return string.format("verified %d templates, %d parts, %d SurfaceAppearances, %d attachments: %d problems", n.templates,
		n.parts, n.surfaces, n.attachments, #problems) .. (if #problems > 0 then "\n  " .. table.concat(problems, "\n  ") else "")
end

return ItemAssets
