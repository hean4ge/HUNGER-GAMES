--[[
	WaterPointsBuilder - edit-time builder for ReplicatedStorage.Shared.WaterPoints (PlayabilityPlan QW10).
	The drinkable water a thirsty newcomer is pointed to on the compass: the lake shore, the river's fords and lowland
	reaches below the falls, the plunge pool, the creek, the marsh outflow and the marsh pools. Candidates come from
	Shared.ArenaLayout; each is kept only where the generated terrain really has water there (ArenaLayout.waterAt,
	at least MIN_DEPTH deep) and inside the starting border. Points closer than SPACING to a kept one are dropped.
	Re-run after TerrainGen or after ArenaLayout's water moves (it rewrites the WaterPoints module source):
	  return require(game.ServerStorage.WorldGen.WaterPointsBuilder:Clone()).build()
]]
local ReplicatedStorage = game:GetService("ReplicatedStorage")

local WaterPointsBuilder = {}

local MIN_DEPTH = 0.4 -- studs of water over the ground
local PLAY_RADIUS = 620 -- inside the starting border (640), with a margin
local SPACING = 22 -- studs between kept points

local function freshLayout()
	-- Studio caches required modules in Edit mode: require a copy
	return require(ReplicatedStorage.Shared.ArenaLayout:Clone())
end

local function every(samples: { any }, step: number, fromS: number?, toS: number?): { Vector3 }
	local out, nextS = {}, nil
	for _, smp in ipairs(samples) do
		local s = smp.s or 0
		if (fromS == nil or s >= fromS) and (toS == nil or s <= toS) and not smp.fall and (smp.gorge or 0) < 0.5 then
			if nextS == nil or s >= nextS then
				table.insert(out, Vector3.new(smp.x, smp.y, smp.z))
				nextS = s + step
			end
		end
	end
	return out
end

function WaterPointsBuilder.collect(): ({ { any } }, { [string]: number })
	local L = freshLayout()
	local candidates: { { any } } = {}
	local function add(p: Vector3, kind: string)
		table.insert(candidates, { p, kind })
	end
	-- the fords first (they're where the trails cross), then the pool
	for _, c in ipairs(L.Crossings or {}) do
		if c.kind == "Ford" then
			add(c.position, "Ford")
		end
	end
	if L.River and L.River.pool then
		add(L.River.pool.center, "Pool")
	end
	-- the lake shore, just inside the water, every 20 degrees around the lake centre
	local lake = L.Lake
	if lake and lake.shoreRadius then
		for phi = 0, 340, 20 do
			local r = lake.shoreRadius(phi) - 5
			local a = math.rad(phi)
			add(Vector3.new(lake.center.X + math.sin(a) * r, lake.level, lake.center.Z - math.cos(a) * r), "Lake")
		end
	end
	-- the river below the falls, the creek and the marsh outflow (no gorge or waterfall samples)
	if L.River and L.River.samples then
		for _, p in ipairs(every(L.River.samples, 40, L.River.poolS)) do
			add(p, "River")
		end
	end
	if L.Creek and L.Creek.samples then
		for _, p in ipairs(every(L.Creek.samples, 32)) do
			add(p, "Creek")
		end
	end
	if L.Outflow and L.Outflow.samples then
		for _, p in ipairs(every(L.Outflow.samples, 24)) do
			add(p, "Stream")
		end
	end
	-- marsh pools: a coarse grid over the marsh
	if L.Marsh and L.isInMarsh then
		local c = L.Marsh.center
		for dx = -120, 120, 24 do
			for dz = -120, 120, 24 do
				local p = Vector3.new(c.X + dx, L.Marsh.level, c.Z + dz)
				if L.isInMarsh(p, -6) then
					add(p, "Marsh")
				end
			end
		end
	end

	-- keep the ones with real water, inside the play area, spaced out
	local kept: { { any } } = {}
	local stats: { [string]: number } = { candidates = #candidates, dry = 0, outside = 0, close = 0 }
	local marshKept = 0
	for _, cand in ipairs(candidates) do
		local p: Vector3, kind: string = cand[1], cand[2]
		local found: Vector3? = nil
		-- lake points that land on the beach step toward the lake centre until they reach water
		local tries = if kind == "Lake" then 6 else 1
		local q = p
		for _ = 1, tries do
			local waterY, depth = L.waterAt(q.X, q.Z)
			if waterY and depth >= MIN_DEPTH then
				found = Vector3.new(q.X, waterY, q.Z)
				break
			end
			if kind ~= "Lake" then
				break
			end
			local toCentre = Vector3.new(lake.center.X - q.X, 0, lake.center.Z - q.Z)
			if toCentre.Magnitude < 4 then
				break
			end
			q += toCentre.Unit * 3
		end
		if not found then
			stats.dry += 1
		elseif L.flatDistance(found) > PLAY_RADIUS then
			stats.outside += 1
		else
			local near = false
			for _, k in ipairs(kept) do
				local d = Vector3.new(k[1].X - found.X, 0, k[1].Z - found.Z).Magnitude
				if d < (if kind == "Marsh" then 45 else SPACING) then
					near = true
					break
				end
			end
			if near or (kind == "Marsh" and marshKept >= 5) then
				stats.close += 1
			else
				table.insert(kept, { found, kind })
				if kind == "Marsh" then
					marshKept += 1
				end
			end
		end
	end
	stats.kept = #kept
	return kept, stats
end

local HEADER = [[
--[=[
	WaterPoints - the drinkable water a thirsty newcomer is pointed to (PlayabilityPlan QW10). Client and server.
	GENERATED by ServerStorage.WorldGen.WaterPointsBuilder (%s, %d points): do not edit by hand, re-run the builder
	after TerrainGen. Each point is { x, waterY, z, kind } at the water's surface; kind is Lake | Ford | Pool |
	River | Creek | Stream | Marsh. Every point was checked against the generated terrain (water at least %.1f deep).
	  WaterPoints.nearest(position, accept?) -> (point: Vector3?, flatDistance: number, kind: string?)
	    accept(point: Vector3, kind: string) -> boolean   optional filter, e.g. only points inside the border
]=]
local WaterPoints = {}

WaterPoints.Points = {
]]

local FOOTER = [[
}

local vectors: { Vector3 } = {}
for i, p in ipairs(WaterPoints.Points) do
	vectors[i] = Vector3.new(p[1], p[2], p[3])
end

function WaterPoints.nearest(position: Vector3, accept: ((Vector3, string) -> boolean)?): (Vector3?, number, string?)
	local best, bestD, bestKind = nil, math.huge, nil
	for i, v in ipairs(vectors) do
		local dx, dz = v.X - position.X, v.Z - position.Z
		local d = dx * dx + dz * dz
		if d < bestD then
			local kind = WaterPoints.Points[i][4]
			if accept == nil or accept(v, kind) then
				best, bestD, bestKind = v, d, kind
			end
		end
	end
	return best, if best then math.sqrt(bestD) else math.huge, bestKind
end

return WaterPoints
]]

-- Rebuilds ReplicatedStorage.Shared.WaterPoints. Returns a one-line report.
function WaterPointsBuilder.build(): string
	local kept, stats = WaterPointsBuilder.collect()
	local byKind: { [string]: number } = {}
	local lines = {}
	for _, k in ipairs(kept) do
		local p: Vector3 = k[1]
		byKind[k[2]] = (byKind[k[2]] or 0) + 1
		table.insert(lines, string.format("\t{ %.1f, %.1f, %.1f, %q },", p.X, p.Y, p.Z, k[2]))
	end
	local date = os.date("%Y-%m-%d")
	-- (a long string drops the newline right after its opening bracket, so HEADER and FOOTER start with their text)
	local source = string.format(HEADER, date, #kept, MIN_DEPTH) .. table.concat(lines, "\n") .. "\n" .. FOOTER
	local shared = ReplicatedStorage:WaitForChild("Shared")
	local module = shared:FindFirstChild("WaterPoints")
	if not module then
		module = Instance.new("ModuleScript")
		module.Name = "WaterPoints"
		module.Parent = shared
	end
	(module :: ModuleScript).Source = source
	local kinds = {}
	for kind, n in pairs(byKind) do
		table.insert(kinds, kind .. " " .. n)
	end
	table.sort(kinds)
	return string.format("WaterPoints: %d kept of %d candidates (%s); dropped %d dry, %d outside, %d too close",
		#kept, stats.candidates, table.concat(kinds, ", "), stats.dry, stats.outside, stats.close)
end

return WaterPointsBuilder
