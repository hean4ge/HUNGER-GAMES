local cache = {}
function FightClips.get(name: string): any
	local fam = FightClips.FAMILY_OF[name]
	if not fam then
		return nil
	end
	local mod = cache[fam]
	if mod == nil then
		local child = script:FindFirstChild(fam)
		local ok, res = pcall(require, child :: any)
		mod = if ok and type(res) == "table" then res else false
		if not ok then
			warn("[FightClips] " .. fam .. ": " .. tostring(res))
		end
		cache[fam] = mod
	end
	local clip = mod and mod.clips[name]
	if clip and clip.family == nil then
		clip.family = fam
	end
	return clip
end

local function exists(name: string?): string?
	return if name and FightClips.FAMILY_OF[name] then name else nil
end

function FightClips.forMove(itemId: string, move: string, n: number?): string?
	local fam = FightClips.WEAPON[itemId]
	local prefix = FightClips.PREFIX[itemId]
	if move == "Light" and prefix then
		return exists(prefix .. "_light_" .. tostring(n or 1))
	elseif move == "HeavyCharge" or move == "Heavy" or move == "Counter" then
		local suffix = if move == "HeavyCharge" then "_heavy_charge" elseif move == "Heavy" then "_heavy" else "_counter"
		return exists(prefix and prefix .. suffix) or exists(fam and FAMILY_PREFIX[fam] and FAMILY_PREFIX[fam] .. suffix)
			or exists(fam == "Axe" and "axe" .. suffix or nil)
	elseif move == "Skill" then
		return exists(fam and SKILL[fam])
	elseif move == "Throw" then
		return exists(THROW[itemId])
	elseif move == "ThrowWind" then
		return exists("throw_wind")
	elseif move == "Equip" then
		return exists(fam and "equip_" .. string.lower(fam))
	end
	return exists(COMMON[move])
end

