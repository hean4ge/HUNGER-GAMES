"""gen_layout.py - writes the generated data tables of the Map 1 layout module.

The module (src/ReplicatedStorage/Shared/ArenaLayout_GreenLand.lua, which the install puts in Shared.ArenaLayout's
place) is written by hand, except for one block between two marker lines. This script rebuilds that block from
two files of the Blender export of Map 1:

  Map1_Layout.json    the 48 plinths, the heart (deck, horn, mouths, sails), the flower beds, the sites
  Map1_Terrain.json   the lake, the stream, the trails, the Edge, the region legend, the map's radii

and writes these tables: Regions, Plates, Heart, Sites, TrailNames, Trails, Stream, Edge, Lake.

It also checks the numbers that are written by hand above the block (BaseHeight, RingHeight, the three radii, the
plinth ring, WaterLevel) against the export, and stops if they disagree: then either the export or the contract
(docs/design/Map1Build.md 3.1) has to change, and that is a person's decision.

  python tools/map1/gen_layout.py                 rewrite the block; says what changed
  python tools/map1/gen_layout.py --check         change nothing; exit 1 if the block on disk is out of date
  python tools/map1/gen_layout.py --stdout        print the block and change nothing
  options:  --exports DIR    the export folder
            --module FILE    the module to rewrite (default: ArenaLayout_GreenLand.lua; if that file is gone because
                             the install has put the Map 1 layout in ArenaLayout.lua, that file)

The export folder is --exports, else the LS_MAP1_EXPORTS environment variable (the same one pack.py reads), else
%USERPROFILE%/OneDrive/Documents/LastStanding/BlenderExports/Map1. The block records the first 12 characters of
each file's SHA-256; they are the same fingerprints as "sources" in tools/map1/pack_manifest.json when the data
pack and the layout were made from the same export.

Only the standard library is used. The module is written as UTF-8 with LF line endings and no BOM (studio_sync
refuses anything else) and must stay under 190,000 bytes (a script Source is capped at 200,000 characters).
After a rewrite: compile-check and push the module (tools/studio_sync/README.md).
"""
import difflib
import hashlib
import json
import math
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
SHARED = os.path.join(REPO, "src", "ReplicatedStorage", "Shared")
MODULE = os.path.join(SHARED, "ArenaLayout_GreenLand.lua")  # before the install
INSTALLED = os.path.join(SHARED, "ArenaLayout.lua")  # after it, if the file above is gone and this one is Map 1's
BEGIN = "-- <<< GENERATED by tools/map1/gen_layout.py"
END = "-- <<< END GENERATED"
MAX_BYTES = 190000
BS = chr(92)

# The ten regions of Map 1, by id. The layout's biome table and Shared.Map1Regions are written against these.
REGIONS = ["Heart", "Iris", "NorthWood", "EastRidge", "SouthMountain", "Lake", "WestRidge", "Edge", "Crest", "Outside"]

# TwoArenas 3.8 names the three trails of the export by the mouth they leave the heart from.
TRAIL_NAMES = {300: "Spiral Path", 60: "Glade Path", 180: "Lake Path"}


def fail(message):
    sys.exit("gen_layout: " + message)


def lp(p):
    """Windows long-path form of p (see tools/studio_sync/sync.py)."""
    p = os.path.abspath(p)
    if os.name == "nt" and not p.startswith(BS + BS):
        return BS + BS + "?" + BS + p
    return p


def read_bytes(p):
    with open(lp(p), "rb") as fh:
        return fh.read()


def option(argv, name):
    """The value after an option, or None when the option is not given."""
    if name not in argv:
        return None
    i = argv.index(name)
    if i + 1 >= len(argv):
        fail(name + " needs a value")
    return argv[i + 1]


def exports_dir(argv):
    if option(argv, "--exports"):
        return option(argv, "--exports")
    env = os.environ.get("LS_MAP1_EXPORTS")
    if env:
        return env
    home = os.environ.get("USERPROFILE") or os.path.expanduser("~")
    return os.path.join(home, "OneDrive", "Documents", "LastStanding", "BlenderExports", "Map1")


# ---------------------------------------------------------------------------------------------------- Lua text
def num(v):
    """A JSON number as Lua source, exact (the shortest text that reads back as the same double)."""
    if isinstance(v, bool) or not isinstance(v, (int, float)):
        fail("expected a number, got %r" % (v,))
    if isinstance(v, float):
        if math.isnan(v) or math.isinf(v):
            fail("the export holds a number that is not finite")
        if v == int(v) and abs(v) < 1e15:
            return str(int(v))  # also turns -0.0 into 0
        return repr(v)
    return str(v)


def string(s):
    if not isinstance(s, str):
        fail("expected text, got %r" % (s,))
    out = s.replace(BS, BS + BS).replace('"', BS + '"').replace("\r", "").replace("\n", BS + "n")
    return '"' + out + '"'


def vec(p):
    if not (isinstance(p, list) and len(p) == 3):
        fail("expected a position [x, y, z], got %r" % (p,))
    return "Vector3.new(%s, %s, %s)" % (num(p[0]), num(p[1]), num(p[2]))


def vecs(points):
    return "{ " + ", ".join(vec(p) for p in points) + " }"


def nums(values):
    return "{ " + ", ".join(num(v) for v in values) + " }"


def comment(text, indent=""):
    """A note from the export as wrapped comment lines."""
    words, lines, line = str(text).split(), [], ""
    for w in words:
        if line and len(indent) * 4 + len(line) + 1 + len(w) > 108:
            lines.append(line)
            line = w
        else:
            line = (line + " " + w) if line else w
    if line:
        lines.append(line)
    return [indent + "-- " + ln for ln in lines]


def need(table, key, where):
    if not isinstance(table, dict) or key not in table:
        fail("%s has no '%s'" % (where, key))
    return table[key]


def close(a, b, tol):
    return abs(float(a) - float(b)) <= tol


def bearing_of(x, z):
    return math.degrees(math.atan2(x, -z)) % 360.0


def angle_gap(a, b):
    return abs(((a - b + 180.0) % 360.0) - 180.0)


# ---------------------------------------------------------------------------------------------------- the block
def build(layout, terrain, sources):
    out = []
    warnings = []
    add = out.append

    radii = need(terrain, "radii", "Map1_Terrain.json")
    plaza = need(terrain, "plaza", "Map1_Terrain.json")
    heart = need(layout, "heart", "Map1_Layout.json")
    items = need(layout, "items", "Map1_Layout.json")
    sites = need(need(layout, "sites", "Map1_Layout.json"), "items", "Map1_Layout.json sites")

    # --- the grid is centred on the origin (Center = 0, 0, 0)
    grid = need(terrain, "grid", "Map1_Terrain.json")
    half = grid["width"] * grid["studsPerPixel"] / 2.0
    if not (close(grid["origin"][0], -half, 1e-6) and close(grid["origin"][1], -half, 1e-6)):
        fail("the export's grid is not centred on the origin: origin %r, half-width %s" % (grid["origin"], half))

    # --- regions: the legend must be the ten the layout's biome table is written for
    legend = need(terrain, "regions", "Map1_Terrain.json")
    got = [legend.get(str(i + 1)) for i in range(len(legend))]
    if got != REGIONS:
        fail("the region legend changed: expected %r, the export has %r. Update REGIONS here and REGION_BIOME in "
             "the module together." % (REGIONS, got))

    add(BEGIN + " (do not edit by hand: re-run the script) >>>")
    add("-- From the Blender export of Map 1 (%s, seed %s):" % (terrain.get("generator", "?"), num(terrain.get("seed", 0))))
    for name, digest, size in sources:
        add("--   %-18s sha256 %s  %s bytes" % (name, digest, "{:,}".format(size)))
    add("-- (tools/map1/pack_manifest.json lists the same fingerprints under \"sources\" when the data pack is from this export.)")
    add("")
    add("-- Regions[id]: Map 1's regions by the id the region grid stores (Shared.Map1Regions.regionAt).")
    add("ArenaLayout.Regions = { " + ", ".join(string(n) for n in REGIONS) + " }")
    add("")

    # --- plates
    plinths = sorted((it for it in items if it.get("asset") == "M1_Plinth"), key=lambda it: it.get("index", -1))
    count = int(need(plaza, "plinths", "plaza"))
    step, offset = float(need(plaza, "plinthStep", "plaza")), float(need(plaza, "plinthOffset", "plaza"))
    ring_r, ring_y = float(need(radii, "plinthRing", "radii")), float(need(plaza, "plinthRingY", "plaza"))
    hp = need(heart, "plinth", "heart")
    stand_h = float(need(hp, "standHeight", "heart.plinth"))
    if len(plinths) != count or int(need(hp, "count", "heart.plinth")) != count:
        fail("plinths: %d M1_Plinth items, plaza.plinths %d, heart.plinth.count %s" % (len(plinths), count, hp.get("count")))
    if not close(count * step, 360.0, 1e-6):
        fail("plinths: %d steps of %s degrees are not a full ring" % (count, step))
    if not close(need(heart, "plinthRingRadius", "heart"), ring_r, 1e-6):
        fail("heart.plinthRingRadius and radii.plinthRing disagree")
    add("-- Plates[i]: launch plate i, in ring order clockwise from north (i = the export's index + 1; its plinth in the")
    add("-- place is workspace.Arena.Plinths.Plinth01 .. Plinth%02d). bearing: degrees. position: the plinth's pivot, on the" % count)
    add("-- turf. stand: where a contender's feet go (the plinth's Stand attachment, %s above the turf). yaw: the plinth" % num(stand_h))
    add("-- mesh's yaw about +Y, as the export places it.")
    add("ArenaLayout.Plates = {")
    for k, it in enumerate(plinths):
        pos, stand, b = need(it, "position", "plinth"), need(it, "stand", "plinth"), float(need(it, "bearing", "plinth"))
        if it.get("index") != k:
            fail("plinths: index %r where %d was expected" % (it.get("index"), k))
        if not close(b, offset + step * k, 0.01):
            fail("plinth %d: bearing %s, expected %s" % (k, b, offset + step * k))
        if not close(math.hypot(pos[0], pos[2]), ring_r, 0.05) or angle_gap(bearing_of(pos[0], pos[2]), b) > 0.02:
            fail("plinth %d: position %r is not at bearing %s, r %s" % (k, pos, b, ring_r))
        if not close(pos[1], ring_y, 0.05):
            fail("plinth %d: y %s, the ring's turf is %s" % (k, pos[1], ring_y))
        if not (close(stand[0], pos[0], 0.001) and close(stand[2], pos[2], 0.001) and close(stand[1] - pos[1], stand_h, 0.01)):
            fail("plinth %d: stand %r is not %s above position %r" % (k, stand, stand_h, pos))
        add("\t{ index = %d, bearing = %s, position = %s, stand = %s, yaw = %s }," % (
            k + 1, num(it["bearing"]), vec(pos), vec(stand), num(need(it, "yawDegrees", "plinth"))))
    add("}")
    add("")

    # --- the heart
    horn = need(heart, "horn", "heart")
    add("-- Heart: the horn's knoll and what stands on it. Y values are world heights.")
    for key in ("heightsNote", "deckNote"):
        if heart.get(key):
            out.extend(comment(heart[key]))
    add("ArenaLayout.Heart = {")
    add("\tknollY = %s, -- the knoll under the platform, level to r = flatTo" % num(need(heart, "knollY", "heart")))
    add("\tflatTo = %s," % num(need(plaza, "flatTo", "plaza")))
    add("\tdeckY = %s, -- the platform deck's walkable top" % num(need(heart, "deckY", "heart")))
    add("\thornPivotY = %s," % num(need(heart, "hornPivotY", "heart")))
    add("\tringRadius = %s, -- the plinth ring" % num(ring_r))
    add("\tringY = %s, -- its turf" % num(ring_y))
    add("\tturfRadius = %s, -- the fresher green disc" % num(need(heart, "turfRadius", "heart")))
    add("\tprotectedDisc = %s, -- the terrain is the designed dome inside the first radius and blends out by the second" % nums(need(radii, "protectedDisc", "radii")))
    add("\tstarPoints = %s, -- bearings of the platform's three points" % nums(need(plaza, "starPoints", "plaza")))
    add("\tdeckPolygon = %s," % vecs(need(heart, "deckPolygon", "heart")))
    add("\tplinth = { count = %d, step = %s, offset = %s, standHeight = %s, drumRadius = %s, tubeRadius = %s, rimOuterRadius = %s }," % (
        count, num(step), num(offset), num(stand_h), num(need(hp, "drumRadius", "heart.plinth")),
        num(need(hp, "tubeRadius", "heart.plinth")), num(need(hp, "rimOuterRadius", "heart.plinth"))))
    add("\thorn = {")
    add("\t\tcolouring = %s," % string(need(horn, "colouring", "heart.horn")))
    add("\t\tfloorY = %s, -- the floor inside the horn" % num(need(horn, "floorY", "heart.horn")))
    add("\t\tfloorTriangle = %s," % vecs(need(horn, "floorTriangle", "heart.horn")))
    add("\t\tfloorInradius = %s," % num(need(horn, "floorInradius", "heart.horn")))
    add("\t\tcoreCornerRadius = %s," % num(need(horn, "coreCornerRadius", "heart.horn")))
    add("\t\tapexY = %s," % num(need(horn, "apexY", "heart.horn")))
    add("\t\ttopY = %s," % num(need(horn, "topY", "heart.horn")))
    if horn.get("rackNote"):
        out.extend(comment(horn["rackNote"], "\t\t"))
    add("\t\trackSpots = %s," % vecs(need(horn, "rackSpots", "heart.horn")))
    add("\t},")
    mouths = need(heart, "mouths", "heart")
    if sorted(float(m["bearing"]) for m in mouths) != sorted(float(b) for b in need(plaza, "mouths", "plaza")):
        fail("heart.mouths and plaza.mouths disagree")
    add("\t-- mouths: the horn's three doorways. threshold = the doorway on the horn's floor; stairTop and stairFoot = the")
    add("\t-- bronze steps from the deck down to the knoll; lane = the open turf from the steps to the plinth ring (no bed")
    add("\t-- lies within halfWidth of the mouth's bearing between fromR and toR).")
    add("\tmouths = {")
    for m in mouths:
        lane = need(m, "lane", "mouth")
        add("\t\t{ bearing = %s, threshold = %s, openingWidth = %s, openingHeight = %s, frameWidthAtDeck = %s," % (
            num(m["bearing"]), vec(need(m, "threshold", "mouth")), num(need(m, "openingWidth", "mouth")),
            num(need(m, "openingHeight", "mouth")), num(need(m, "frameWidthAtDeck", "mouth"))))
        add("\t\t\tstairTop = %s, stairFoot = %s, stairWidth = %s, stairRisers = %s, stairRise = %s," % (
            vec(need(m, "stairTop", "mouth")), vec(need(m, "stairFoot", "mouth")), num(need(m, "stairWidth", "mouth")),
            num(need(m, "stairRisers", "mouth")), num(need(m, "stairRise", "mouth"))))
        add("\t\t\tlane = { halfWidth = %s, fromR = %s, toR = %s } }," % (
            num(need(lane, "halfWidth", "lane")), num(need(lane, "fromR", "lane")), num(need(lane, "toR", "lane"))))
    add("\t},")
    sails = need(heart, "sails", "heart")
    if sails and sails[0].get("note"):
        out.extend(comment("sails: one at each star point. " + sails[0]["note"], "\t"))
    add("\tsails = {")
    for s in sails:
        add("\t\t{ bearing = %s, hemTip = %s, tip = %s, finTip = %s }," % (
            num(need(s, "bearing", "sail")), vec(need(s, "hemTip", "sail")), vec(need(s, "tip", "sail")), vec(need(s, "finTip", "sail"))))
    add("\t},")
    beds = sorted((it for it in items if re.match(r"^M1_Spoke_\d+$", str(it.get("asset")))), key=lambda it: it["bearing"])
    if [float(b["bearing"]) for b in beds] != sorted(float(b) for b in need(plaza, "bedBearings", "plaza")):
        fail("the M1_Spoke items and plaza.bedBearings disagree")
    add("\t-- beds: the %d lens-shaped flower beds, laid like spokes from innerR to outerR along their bearing; position =" % len(beds))
    add("\t-- the bed mesh's pivot (its middle), yaw = its yaw about +Y. Mounded 1 to 1.5 above the turf.")
    add("\tbeds = {")
    for b in beds:
        add("\t\t{ asset = %s, bearing = %s, colour = %s, length = %s, width = %s, innerR = %s, outerR = %s, position = %s, yaw = %s }," % (
            string(b["asset"]), num(b["bearing"]), string(need(b, "colour", "bed")), num(need(b, "length", "bed")),
            num(need(b, "width", "bed")), num(need(b, "innerR", "bed")), num(need(b, "outerR", "bed")),
            vec(need(b, "position", "bed")), num(need(b, "yawDegrees", "bed"))))
    add("\t},")
    tears = [it for it in items if str(it.get("asset", "")).startswith("M1_Teardrop")]
    add("\t-- teardrops: the %d big pale petals, one on each side of each mouth lane, laid along it with the round end toward" % len(tears))
    add("\t-- the horn. lane = the mouth's bearing; side = which side of the lane, facing out from the horn.")
    add("\tteardrops = {")
    for t in tears:
        note = str(t.get("note", ""))
        side = "left" if "left facing out" in note else ("right" if "right facing out" in note else "")
        if not side:
            warnings.append("teardrop %s at %r: its note does not say left or right" % (t.get("asset"), t.get("position")))
        add("\t\t{ asset = %s, lane = %s, side = %s, colour = %s, length = %s, width = %s, position = %s, yaw = %s }," % (
            string(t["asset"]), num(need(t, "bearing", "teardrop")), string(side), string(need(t, "colour", "teardrop")),
            num(need(t, "length", "teardrop")), num(need(t, "width", "teardrop")), vec(need(t, "position", "teardrop")),
            num(need(t, "yawDegrees", "teardrop"))))
    add("\t},")
    add("}")
    add("")
    known_heart = {"note", "knollY", "deckY", "hornPivotY", "turfRadius", "plinthRingRadius", "heightsNote", "plinth",
                   "deckPolygon", "deckNote", "horn", "mouths", "sails"}
    for key in sorted(set(heart) - known_heart):
        warnings.append("Map1_Layout.json heart has a key this script does not write: " + key)

    # --- sites
    note = need(layout, "sites", "Map1_Layout.json").get("note")
    add("-- Sites: the design's places as points on the ground (TwoArenas 3.6 and 3.9): rings B, C and D, the eight")
    add("-- runner's flags (F) and seven single berms (S). position.Y is the ground there in the export. built = what the")
    add("-- export really made there; no built = a design anchor only, nothing stands there yet.")
    if note:
        out.extend(comment("From the export: " + note))
    add("ArenaLayout.Sites = {")
    seen = set()
    for s in sites:
        sid = need(s, "id", "site")
        if sid in seen:
            fail("two sites share the id " + sid)
        seen.add(sid)
        pos = need(s, "position", "site " + sid)
        if need(s, "region", "site " + sid) not in REGIONS:
            fail("site %s is in an unknown region %r" % (sid, s["region"]))
        if not close(math.hypot(pos[0], pos[2]), s["r"], 0.6) or (s["r"] > 1 and angle_gap(bearing_of(pos[0], pos[2]), s["bearing"]) > 0.1):
            fail("site %s: position %r is not at bearing %s, r %s" % (sid, pos, s["bearing"], s["r"]))
        built = s.get("built")
        built_text = ""
        if isinstance(built, str) and built and not built.lower().startswith("nothing"):
            built_text = ", built = " + string(built)
        add("\t{ id = %s, name = %s, bearing = %s, r = %s, position = %s, region = %s, slopeDegrees = %s, waterWithin32 = %s%s }," % (
            string(sid), string(need(s, "name", "site")), num(s["bearing"]), num(s["r"]), vec(pos), string(s["region"]),
            num(need(s, "slopeDegrees", "site")), "true" if need(s, "waterWithin32", "site") else "false", built_text))
    add("}")
    add("")

    # --- trails
    trails = need(terrain, "trails", "Map1_Terrain.json")
    names = []
    for i, tr in enumerate(trails):
        b = bearing_of(tr[0][0], tr[0][2])
        name = next((n for a, n in TRAIL_NAMES.items() if angle_gap(a, b) < 1.0), None)
        if not name:
            name = "Trail %d" % (i + 1)
            warnings.append("trail %d leaves the heart at bearing %.1f: no name is known for it" % (i + 1, b))
        names.append(name)
    add("-- Trails[i]: the control points of each bare-earth path, heart outwards, Y = 0 (the v2 format). The path painted")
    add("-- into the terrain is a Catmull-Rom curve through them. TrailNames[i] is its name (TwoArenas 3.8).")
    add("ArenaLayout.TrailNames = { " + ", ".join(string(n) for n in names) + " }")
    add("ArenaLayout.Trails = {")
    for tr in trails:
        add("\t" + vecs(tr) + ",")
    add("}")
    add("")

    # --- the stream
    stream = need(terrain, "stream", "Map1_Terrain.json")
    pts, levels = need(stream, "pointsRoblox", "stream"), need(stream, "waterLevels", "stream")
    if len(pts) != len(levels) or len(pts) < 2:
        fail("stream: %d points and %d water levels" % (len(pts), len(levels)))
    lake = need(terrain, "lake", "Map1_Terrain.json")
    if any(levels[i] < levels[i + 1] - 1e-9 for i in range(len(levels) - 1)):
        fail("stream: the water levels rise downstream")
    if not close(levels[-1], lake["level"], 1e-6):
        fail("stream: it ends at level %s, the lake is at %s" % (levels[-1], lake["level"]))
    add("-- Stream: the one stream, from its spring in the north-west to the lake. points[i] = the centreline, with Y = the")
    add("-- DESIGNED water level there. The water in the game is voxels written from the data pack after its repairs (sills")
    add("-- between pools, levels snapped into their voxel layer): read the real surface from the terrain, not from here.")
    if stream.get("note"):
        out.extend(comment("From the export: " + stream["note"]))
    add("ArenaLayout.Stream = {")
    add("\thalfWidth = %s," % num(need(stream, "halfWidth", "stream")))
    add("\tpoints = {")
    row = []
    for p, lv in zip(pts, levels):
        row.append(vec([p[0], lv, p[2]]))
        if len(row) == 3:
            add("\t\t" + ", ".join(row) + ",")
            row = []
    if row:
        add("\t\t" + ", ".join(row) + ",")
    add("\t},")
    add("}")
    add("")

    # --- the Edge
    edge = need(terrain, "edge", "Map1_Terrain.json")
    sector = need(edge, "sector", "edge")
    add("-- Edge: the cliff in the north. lipR = the lip's nominal radius (the real lip wanders: see the header); sector =")
    add("-- the bearings either side of north that the cliff spans; the ground above it is about canyonFloorY + cliffDrop.")
    add("ArenaLayout.Edge = { lipR = %s, cliffDrop = %s, canyonFloorY = %s, sector = %s }" % (
        num(need(edge, "lipR", "edge")), num(need(edge, "cliffDrop", "edge")), num(need(edge, "canyonFloorY", "edge")), nums(sector)))
    add("")

    # --- the lake
    centre, axes = need(lake, "centre", "lake"), need(lake, "semiAxesStuds", "lake")
    add("-- Lake: an ellipse. center.Y = the water level; radiusX = the east-west semi-axis, radiusZ = the north-south one.")
    add("ArenaLayout.Lake = { level = %s, center = %s, radiusX = %s, radiusZ = %s, depth = %s }" % (
        num(lake["level"]), vec([centre[0], lake["level"], centre[2]]), num(axes[0]), num(axes[1]), num(need(lake, "maxDepth", "lake"))))
    add(END + " >>>")

    expected = {
        "BaseHeight": float(need(plaza, "knollY", "plaza")),
        "RingHeight": ring_y,
        "PlayRadius": float(need(radii, "play", "radii")),
        "BoundaryRadius": float(need(radii, "boundary", "radii")),
        "TerrainRadius": float(need(radii, "terrainTo", "radii")),
        "PlinthRingRadius": ring_r,
        "PlinthCount": float(count),
        "PlinthOffsetDeg": offset,
        "WaterLevel": float(lake["level"]),
    }
    if not close(heart["knollY"], plaza["knollY"], 1e-6):
        fail("heart.knollY and plaza.knollY disagree")
    counts = "%d plates, %d beds, %d teardrops, %d mouths, %d sails, %d sites, %d trails, %d stream points" % (
        len(plinths), len(beds), len(tears), len(mouths), len(sails), len(sites), len(trails), len(pts))
    return out, expected, warnings, counts


def check_core_numbers(text, expected):
    """The hand-written numbers above the block must agree with the export."""
    found = {m.group(1): float(m.group(2)) for m in re.finditer(r"(?m)^ArenaLayout\.(\w+)\s*=\s*(-?\d+(?:\.\d+)?)\b", text)}
    problems = []
    for name, want in sorted(expected.items()):
        if name not in found:
            problems.append("the module does not set ArenaLayout.%s (the export says %s)" % (name, num(want)))
        elif not close(found[name], want, 1e-9):
            problems.append("ArenaLayout.%s is %s in the module and %s in the export" % (name, num(found[name]), num(want)))
    if problems:
        fail("the hand-written numbers and the export disagree:\n  " + "\n  ".join(problems))


def shown(path):
    """The path as the messages show it: relative to the repo when it is inside it."""
    try:
        rel = os.path.relpath(path, REPO)
    except ValueError:  # another drive
        return path
    return path if rel.startswith("..") else rel


def default_module():
    """ArenaLayout_GreenLand.lua; once the install has put the Map 1 layout in ArenaLayout.lua, that file."""
    if os.path.isfile(lp(MODULE)):
        return MODULE
    if os.path.isfile(lp(INSTALLED)) and (BEGIN.encode("utf-8") in read_bytes(INSTALLED)):
        return INSTALLED
    return MODULE


def main(argv):
    exports = exports_dir(argv)
    module = option(argv, "--module") or default_module()
    sources, data = [], {}
    for name in ("Map1_Layout.json", "Map1_Terrain.json"):
        path = os.path.join(exports, name)
        if not os.path.isfile(lp(path)):
            fail("not found: " + path)
        raw = read_bytes(path)
        sources.append((name, hashlib.sha256(raw).hexdigest()[:12], len(raw)))
        data[name] = json.loads(raw.decode("utf-8"))
    block, expected, warnings, counts = build(data["Map1_Layout.json"], data["Map1_Terrain.json"], sources)
    for w in warnings:
        print("warning: " + w)
    if "--stdout" in argv:
        sys.stdout.write("\n".join(block) + "\n")
        return 0

    if not os.path.isfile(lp(module)):
        fail("the module does not exist: %s (it is written by hand; this script only fills its generated block)" % module)
    raw = read_bytes(module)
    if b"\r" in raw or raw.startswith(b"\xef\xbb\xbf"):
        fail("the module has CR line endings or a BOM; Studio sources are UTF-8 with LF only")
    lines = raw.decode("utf-8").split("\n")
    begins = [i for i, ln in enumerate(lines) if ln.startswith(BEGIN)]
    ends = [i for i, ln in enumerate(lines) if ln.startswith(END)]
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        fail("the module needs exactly one line starting '%s' and, after it, one starting '%s'" % (BEGIN, END))
    hand = "\n".join(lines[: begins[0]] + lines[ends[0] + 1:])
    check_core_numbers(hand, expected)
    new_lines = lines[: begins[0]] + block + lines[ends[0] + 1:]
    new = "\n".join(new_lines).encode("utf-8")
    if len(new) >= MAX_BYTES:
        fail("the module would be %d bytes; it must stay under %d" % (len(new), MAX_BYTES))
    same = new == raw
    if "--check" in argv:
        print("%s: the generated block is %s (%s; module %d bytes)" % (
            shown(module), "up to date" if same else "OUT OF DATE", counts, len(raw)))
        return 0 if same else 1
    if same:
        print("unchanged: %s (%s; %d bytes)" % (shown(module), counts, len(raw)))
        return 0
    with open(lp(module), "wb") as fh:
        fh.write(new)
    old_block = lines[begins[0]: ends[0] + 1]
    # the first two lines of a unified diff are its file headers; a removed Lua comment also starts "---"
    diff = [ln for ln in list(difflib.unified_diff(old_block, block, lineterm="", n=0))[2:] if ln[:1] in ("+", "-")]
    print("rewrote the generated block of %s: %s; %d lines out, %d lines in; module %d bytes (limit %d)" % (
        shown(module), counts, sum(1 for ln in diff if ln[0] == "-"), sum(1 for ln in diff if ln[0] == "+"),
        len(new), MAX_BYTES))
    print("next: python tools/studio_sync/sync.py check %s" % shown(module).replace(BS, "/"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
