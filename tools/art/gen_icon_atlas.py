"""Generate src/ReplicatedStorage/Shared/IconAtlas.lua from the uploaded icon sheets' atlas files.

Sources (art/icons): IconAtlas.json (Icons_1..5, Ranks_1..3, Banners_1..3) and SkinTiles.json (SkinTiles_1..4).
Every rectangle is copied exactly (x, y, w, h in sheet pixels). Run from the repo root:

    python tools/art/gen_icon_atlas.py
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ICONS = os.path.join(ROOT, "art", "icons")
OUT = os.path.join(ROOT, "src", "ReplicatedStorage", "Shared", "IconAtlas.lua")


def lua_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    atlas = json.load(open(os.path.join(ICONS, "IconAtlas.json"), encoding="utf-8"))
    tiles = json.load(open(os.path.join(ICONS, "SkinTiles.json"), encoding="utf-8"))

    sheets = {}
    for src in (atlas["sheets"], tiles["sheets"]):
        for name, s in src.items():
            aid = s.get("assetId") or ""
            if not aid.startswith("rbxassetid://"):
                sys.exit("sheet %s has no rbxassetid" % name)
            sheets[name] = (aid, s["size"][0], s["size"][1])

    cells = []
    for name, c in atlas["icons"].items():
        cells.append((name, c["sheet"], c["x"], c["y"], c["w"], c["h"], c.get("group", ""), c.get("name", "")))
    for name, c in tiles["tiles"].items():
        cells.append((name, c["sheet"], c["x"], c["y"], c["w"], c["h"], "SkinTiles", ""))
    for cell in cells:
        if cell[1] not in sheets:
            sys.exit("cell %s names unknown sheet %s" % (cell[0], cell[1]))
        _, sw, sh = sheets[cell[1]]
        if cell[2] < 0 or cell[3] < 0 or cell[2] + cell[4] > sw or cell[3] + cell[5] > sh:
            sys.exit("cell %s lies outside its sheet" % cell[0])

    out = []
    out.append("--[[")
    out.append("\tIconAtlas - GENERATED by tools/art/gen_icon_atlas.py from art/icons/IconAtlas.json and SkinTiles.json.")
    out.append("\tDo not edit by hand: change the Blender generator or the atlas files and run the script again.")
    out.append("")
    out.append("\tThe 15 uploaded icon sheets (art/blender/ui_icons.py; uploaded 20 Nov 2026, owner approved) and every cell")
    out.append("\ton them, exactly as drawn. Sheets[name] = { Image, W, H }. Cells[name] = { Sheet, X, Y, W, H, Group, Title }:")
    out.append("\tImageRectOffset = (X, Y), ImageRectSize = (W, H) on Sheets[Sheet].Image. Shared.Icons draws them.")
    out.append("]]")
    out.append("")
    out.append("export type Cell = { Sheet: string, X: number, Y: number, W: number, H: number, Group: string, Title: string }")
    out.append("")
    out.append("local IconAtlas = {}")
    out.append("")
    out.append("IconAtlas.Sheets = {")
    for name in sorted(sheets):
        aid, w, h = sheets[name]
        out.append("\t%s = { Image = %s, W = %d, H = %d }," % (name, lua_str(aid), w, h))
    out.append("}")
    out.append("")
    out.append("IconAtlas.Cells = {")
    for name, sheet, x, y, w, h, group, title in cells:
        out.append("\t%s = { Sheet = %s, X = %d, Y = %d, W = %d, H = %d, Group = %s, Title = %s }," % (
            name, lua_str(sheet), x, y, w, h, lua_str(group), lua_str(title)))
    out.append("} :: { [string]: Cell }")
    out.append("")
    out.append("return IconAtlas")
    out.append("")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote %s: %d sheets, %d cells" % (os.path.relpath(OUT, ROOT), len(sheets), len(cells)))


if __name__ == "__main__":
    main()
