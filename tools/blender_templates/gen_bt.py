# Generates src/ServerStorage/WorldGen/BlenderData.lua (compact data from the three uploaded Blender manifests).
import json, os, sys
REPO = sys.argv[1]
MAN = os.path.join(REPO, 'art', 'manifests')
def r(x, n=4):
    v = round(float(x), n)
    s = ('%.' + str(n) + 'f') % v
    s = s.rstrip('0').rstrip('.')
    return '0' if s in ('-0', '') else s
def vec(v): return '{' + ','.join(r(a) for a in v) + '}'
def part(p):
    return '{n="%s",c={%d,%d,%d},m="%s",t=%s,col=%s,q=%s,sh=%s,p=%s,s=%s}' % (
        p['name'], *p['rgb'], p['robloxMaterial'], r(p.get('transparency', 0) or 0),
        'true' if p.get('collide') else 'false', 'true' if p.get('canQuery') else 'false',
        'true' if p.get('castShadow', True) else 'false', vec(p['center']), vec(p['size']))
def att(name, a):
    return '["%s"]={p=%s,l=%s,u=%s}' % (name, vec(a['position']), vec(a['look']), vec(a.get('up', [0, 1, 0])))
out = ['-- GENERATED by tools/blender_templates/gen_bt.py (python tools/blender_templates/gen_bt.py .) from art/manifests/{Creatures,TreesClimb,TrainLobby}.manifest.json.',
       '-- Do not edit by hand: re-run the generator. Read by WorldGen.BlenderTemplates.', 'return {']
for cat in ['Creatures', 'TreesClimb', 'TrainLobby']:
    d = json.load(open(os.path.join(MAN, cat + '.manifest.json')))
    aid = d['assetIds']['model']['assetId']
    out.append('\t%s = { assetId = %d, assets = {' % (cat, aid))
    for a in d['assets']:
        if cat == 'TreesClimb' and a['name'].endswith('_Far'):
            continue
        fields = ['parts={' + ','.join(part(p) for p in a['parts']) + '}']
        if a.get('attachments'):
            fields.append('att={' + ','.join(att(k, v) for k, v in a['attachments'].items()) + '}')
        if a.get('climb'):
            c = a['climb']
            fields.append('climb={trunk=%s,limbs={%s}}' % (r(c['trunk']), ','.join(
                '{y=%s,bearing=%s,length=%s,width=%s,thick=%s}' % (r(l['y']), r(l['bearing']), r(l['length']), r(l['width']), r(l['thick'])) for l in c['limbs'])))
        if a.get('colliders') is not None:
            fields.append('colliders={' + ','.join('{n="%s",p=%s,s=%s,yaw=%s}' % (k['name'], vec(k['center']), vec(k['size']), r(k.get('yawDeg', 0))) for k in a['colliders']) + '}')
        if a.get('placement'):
            fields.append('placement={p=%s,yaw=%s}' % (vec(a['placement']['position']), r(a['placement'].get('yawDeg', 0))))
        if a.get('placements'):
            fields.append('placements={' + ','.join('{p=%s,yaw=%s}' % (vec(x['position']), r(x.get('yawDeg', 0))) for x in a['placements']) + '}')
        if a.get('scenery'):
            sp = a['scenery'].get('suggestedSpeedStudsPerSecond', {})
            fields.append('speeds={' + ','.join('["%s"]=%s' % (k, r(v)) for k, v in sp.items()) + '}')
            fields.append('length=%s' % r(a['scenery'].get('length', 400)))
        if a.get('hitbox'):
            fields.append('hitbox={p=%s,s=%s}' % (vec(a['hitbox']['center']), vec(a['hitbox']['size'])))
        out.append('\t\t["%s"] = {%s},' % (a['name'], ','.join(fields)))
    out.append('\t} },')
    if cat == 'TrainLobby':
        ms = d['markers']
        out.append('\tTrainMarkers = {' + ','.join('["%s"]={p=%s,l=%s,car="%s"}' % (k, vec(v['position']), vec(v['look']), v.get('car', '')) for k, v in ms.items()) + '},')
        bd = [a for a in d['assets'] if a.get('boards')][0]['boards']
        out.append('\tTrainBoards = {' + ','.join('["%s"]={w=%s,h=%s}' % (k, r(v['size'][0]), r(v['size'][1])) for k, v in bd.items()) + '},')
out.append('}')
path = os.path.join(REPO, 'src', 'ServerStorage', 'WorldGen', 'BlenderData.lua')
open(path, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
print(path, os.path.getsize(path))
